function Carousel({ group, L, onOpen }) {
  const ref = useRef(null);
  const scroll = (dir) => ref.current?.scrollBy({ left: dir * 300, behavior: 'smooth' });
  return (
    <div style={{ marginBottom: '28px' }}>
      <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '12px' }}>
        <h3 style={{ margin: 0, fontSize: '18px', color: '#212529' }}>{group.category}</h3>
        <div style={{ display: 'flex', gap: '8px' }}>
          <button className="lp-arrow" onClick={() => scroll(-1)} aria-label="prev">‹</button>
          <button className="lp-arrow" onClick={() => scroll(1)} aria-label="next">›</button>
        </div>
      </div>
      <div ref={ref} className="lp-row">
        {group.items.map((tc, i) => (
          <div key={i} className="lp-card" onClick={() => onOpen({ ...tc, color: group.color, category: group.category })}>
            <div style={{ height: '8px', backgroundColor: group.color }} />
            <div style={{ padding: '14px 16px', display: 'flex', flexDirection: 'column', gap: '10px', flex: 1 }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                <span style={{ fontWeight: 700, fontSize: '13px', color: group.color }}>{tc.id}</span>
                <span style={{ fontSize: '11px', fontWeight: 700, padding: '2px 8px', borderRadius: '10px', backgroundColor: priorityColors[tc.priority].bg, color: priorityColors[tc.priority].fg }}>{tc.priority}</span>
              </div>
              <div style={{ fontWeight: 600, fontSize: '15px', color: '#212529', lineHeight: 1.35, flex: 1 }}>{tc.title}</div>
              <div style={{ fontSize: '12px', color: '#6c757d', display: 'flex', gap: '12px' }}>
                <span>🪜 {tc.steps.length} {L.steps}</span>
                <span>🔗 {tc.reqs} {L.reqs}</span>
              </div>
            </div>
          </div>
        ))}
      </div>
    </div>
  );
}

