export function authErrorMessage(err, L) {
  const data = err?.response?.data;
  const code = data?.code;
  const fn = code && L.errors[code];
  if (typeof fn === 'function') return fn(data.seconds ?? '');
  if (fn) return fn;
  if (!err?.response) return L.errors.network;
  return (data && (data.message || (typeof data === 'string' ? data : ''))) || L.errors.network;
}
